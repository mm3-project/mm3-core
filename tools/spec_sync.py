"""Regenerate ``docs/spec/requirements.toml`` and ``versions.toml`` from the specs.

Implements:
    CORE-71, CORE-75, CORE-76: Core spec 0.6, §10.3 Documentation and quality.

Usage::

    python tools/spec_sync.py           # rewrite the generated files
    python tools/spec_sync.py --check   # fail if they are out of date (CI)

Input: the Markdown exports ``docs/spec/core.md`` and ``docs/spec/contract.md``.
For each requirement the tool records its spec, section, title, a hash of its
text, ``introduced_in`` and ``changed_in`` (taken from the Document history
rows, CORE-76). It fails when a requirement's text changed, or a requirement
was added or removed, without being listed in a history row newer than the
previous sync.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

from spec_lib import SPEC_DIR, SPECS, load_requirements, load_spec_docs, version_key

URLS = {
    "Core spec": "https://claude.ai/artifact/FMsTUUoBP9wHzFtruUa6FV",
    "Module Contract": "https://claude.ai/artifact/AwhPKtk3ezmyix1NRmKZrR",
}
KEYS = {"Core spec": "core", "Module Contract": "contract"}


def text_hash(text: str) -> str:
    """Hash a requirement text, ignoring Markdown escapes and spacing.

    Args:
        text: Requirement text.

    Returns:
        First 12 hex digits of its SHA-256.
    """
    norm = re.sub(r"\s+", " ", text.replace("\\", "").replace("`", "")).strip()
    return hashlib.sha256(norm.encode()).hexdigest()[:12]


def _q(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _sort_key(rid: str) -> tuple[int, int]:
    prefix, num = rid.split("-")
    return ({"CORE": 0, "WGT": 1, "CLK": 2, "WTH": 3, "MOD": 4}[prefix], int(num))


def build(spec_dir: Path) -> tuple[str, str, list[str]]:
    """Compute the generated files.

    Args:
        spec_dir: Directory with the spec exports and the previous outputs.

    Returns:
        Text of ``requirements.toml``, text of ``versions.toml``, and errors.
    """
    docs = load_spec_docs(spec_dir)
    previous = load_requirements(spec_dir)
    prev_versions: dict[str, str] = {}
    if previous:
        import tomllib

        data = tomllib.loads((spec_dir / "requirements.toml").read_text())
        prev_versions = {s["name"]: s["version"] for s in data.get("spec", [])}

    errors: list[str] = []
    records: dict[str, dict[str, str]] = {}
    for name, doc in docs.items():
        old_first = sorted(doc.versions, key=version_key)
        since = prev_versions.get(name)

        def newer(ver: str, since: str | None = since) -> bool:
            return since is None or version_key(ver) > version_key(since)

        for rid, req in doc.requirements.items():
            mentions = [v for v in old_first if rid in doc.history.get(v, [])]
            rec = {
                "id": rid,
                "spec": name,
                "section": req["section"],
                "title": req["title"],
                "hash": text_hash(req["text"]),
                "introduced_in": mentions[0] if mentions else old_first[0],
                "changed_in": mentions[-1] if mentions else old_first[0],
                "status": "active",
            }
            prev = previous.get(rid)
            if prev is not None:
                rec["introduced_in"] = prev["introduced_in"]
            elif previous:
                rec["introduced_in"] = rec["changed_in"]
            if previous and since is not None:
                if prev is None and not newer(rec["changed_in"]):
                    errors.append(
                        f"{rid}: new requirement not listed in a history row after {since}"
                    )
                elif (
                    prev is not None
                    and prev.get("status") == "active"
                    and prev["hash"] != rec["hash"]
                    and not newer(rec["changed_in"])
                ):
                    errors.append(
                        f"{rid}: text changed but not listed in a history row after {since}"
                    )
            records[rid] = rec
        for rid, prev in previous.items():
            if prev["spec"] != name or rid in records:
                continue
            removed = dict(prev)
            if prev.get("status") == "active":
                listed = [v for v in old_first if rid in doc.history.get(v, []) and newer(v)]
                if not listed:
                    errors.append(f"{rid}: removed but not listed in a history row after {since}")
                removed["status"] = "removed"
                removed["removed_in"] = doc.version
            records[rid] = removed

    out = [
        "# Generated by tools/spec_sync.py from docs/spec/*.md - do not edit (CORE-75).",
        "",
    ]
    for name, doc in docs.items():
        out += [
            "[[spec]]",
            f"name = {_q(name)}",
            f"file = {_q(SPECS[name]['file'])}",
            f"version = {_q(doc.version)}",
            "versions = [" + ", ".join(_q(v) for v in sorted(doc.versions, key=version_key)) + "]",
            "",
        ]
    for rid in sorted(records, key=_sort_key):
        rec = records[rid]
        out.append("[[requirement]]")
        for key in (
            "id",
            "spec",
            "section",
            "title",
            "hash",
            "introduced_in",
            "changed_in",
            "status",
            "removed_in",
        ):
            if key in rec:
                out.append(f"{key} = {_q(str(rec[key]))}")
        out.append("")
    req_text = "\n".join(out)

    ver = [
        "# Current versions of the specifications (generated by tools/spec_sync.py).",
        "# Code may cite any version listed in requirements.toml (CORE-77).",
        "",
    ]
    for name, doc in docs.items():
        ver += [
            f"[{KEYS[name]}]",
            f"name = {_q(name)}",
            f"version = {_q(doc.version)}",
            f"url = {_q(URLS[name])}",
            "",
        ]
    return req_text, "\n".join(ver), errors


def main(argv: list[str] | None = None) -> int:
    """Run the sync.

    Args:
        argv: Command-line arguments.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if files are out of date")
    parser.add_argument("--spec-dir", type=Path, default=SPEC_DIR)
    args = parser.parse_args(argv)
    req_text, ver_text, errors = build(args.spec_dir)
    for err in errors:
        print(f"ERROR {err}")
    if errors:
        return 1
    targets = {
        args.spec_dir / "requirements.toml": req_text,
        args.spec_dir / "versions.toml": ver_text,
    }
    if args.check:
        stale = [p.name for p, t in targets.items() if not p.exists() or p.read_text() != t]
        if stale:
            print(f"ERROR out of date: {', '.join(stale)}; run python tools/spec_sync.py")
            return 1
        print("spec sync: up to date")
        return 0
    for path, text in targets.items():
        path.write_text(text)
    print(f"wrote {', '.join(p.name for p in targets)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
